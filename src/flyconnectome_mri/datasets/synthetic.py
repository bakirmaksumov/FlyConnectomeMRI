"""Generate a tiny SYNTHETIC image dataset for testing the pipeline.

THIS IS NOT MEDICAL DATA. The images are drawn shapes: a grey ellipse
("head") with noise; "tumor" images additionally contain a bright disk. They
exist only so the data pipeline can be exercised and tested without a real
MRI dataset. No result obtained on them says anything about MRI.

Each synthetic "patient" has several "slices" (images) and one label, mimicking
the structure that makes patient-level splitting necessary in real data.
File names: ``P0001_s00.png`` (patient P0001, slice 0).
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from PIL import Image

README_TEXT = (
    "SYNTHETIC DATA - NOT MEDICAL IMAGES.\n"
    "Generated by flyconnectome_mri.datasets.synthetic for pipeline testing only.\n"
)


def make_synthetic_dataset(
    root: Path,
    patients_per_class: int = 10,
    slices_per_patient: int = 4,
    image_size: int = 64,
    seed: int = 0,
    classes: tuple[str, str] = ("normal", "tumor"),
) -> Path:
    """Write ``root/<class>/P####_s##.png`` images deterministically; returns ``root``."""
    rng = np.random.default_rng(seed)
    root.mkdir(parents=True, exist_ok=True)
    (root / "README.txt").write_text(README_TEXT, encoding="utf-8")
    yy, xx = np.mgrid[0:image_size, 0:image_size] / image_size

    patient_number = 0
    for class_index, class_name in enumerate(classes):
        folder = root / class_name
        folder.mkdir(exist_ok=True)
        for _ in range(patients_per_class):
            patient_number += 1
            # Per-patient anatomy: head size/position shared by all of this patient's slices.
            cx, cy = 0.5 + rng.normal(0, 0.03, 2)
            rx, ry = rng.uniform(0.30, 0.40, 2)
            lesion = (rng.uniform(0.4, 0.6), rng.uniform(0.4, 0.6), rng.uniform(0.05, 0.10))
            for slice_index in range(slices_per_patient):
                head = ((xx - cx) / rx) ** 2 + ((yy - cy) / ry) ** 2 <= 1.0
                image = 0.1 + 0.4 * head + rng.normal(0, 0.05, (image_size, image_size))
                if class_index == 1:
                    lx, ly, r = lesion
                    r *= 1.0 - 0.15 * slice_index  # lesion shrinks across slices
                    image += 0.4 * (((xx - lx) ** 2 + (yy - ly) ** 2) <= r**2)
                pixels = (np.clip(image, 0, 1) * 255).astype(np.uint8)
                Image.fromarray(pixels, mode="L").save(folder / f"P{patient_number:04d}_s{slice_index:02d}.png")
    return root
